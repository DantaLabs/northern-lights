#!/usr/bin/env python3
"""Generate the real, git-ignored sandbox mapping file from the committed example.

Usage (from the repository root):
    python3 -I configs/demo/make_sandbox_mappings.py \
        --example configs/demo/mappings-sandbox.example.yaml \
        --placeholders docs/demo/evidence/2026-10-19-RB-01/step-3.json \
        --real STEP3_LOCAL_JSON --document STEP2_LOCAL_JSON \
        --out configs/demo/mappings-sandbox.yaml

Each <id-NN> in the example is mapped to the real ID found at the same position
in the placeholder JSON and in the local JSON with real IDs. <document-id> comes
from the report document named "2025 Annual Report - EN" in the document list.
Only counts are printed, never IDs. Exit codes: 0 ok, 1 failure.
"""
import argparse
import json
import re
import subprocess
import sys

PLACEHOLDER_RE = re.compile(r"<id-\d{2}>")
ANY_PLACEHOLDER_RE = re.compile(r"<(?:id-\d+|document-id)>")
DOC_NAME = "2025 Annual Report - EN"


def load(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def maybe_json(text):
    if text[:1] in "{[":
        try:
            return json.loads(text)
        except ValueError:
            return None
    return None


def pair(ph, real, out):
    """Walk the two documents in parallel and record placeholder -> real ID."""
    if isinstance(ph, dict) and isinstance(real, dict):
        for key, value in ph.items():
            if key in real:
                pair(value, real[key], out)
    elif isinstance(ph, list) and isinstance(real, list):
        for a, b in zip(ph, real):
            pair(a, b, out)
    elif isinstance(ph, str) and isinstance(real, str):
        inner_ph, inner_real = maybe_json(ph), maybe_json(real)
        if inner_ph is not None and inner_real is not None:
            pair(inner_ph, inner_real, out)
            return
        if not PLACEHOLDER_RE.search(ph):
            return
        parts = PLACEHOLDER_RE.split(ph)
        names = PLACEHOLDER_RE.findall(ph)
        regex = "^" + "(.+?)".join(re.escape(p) for p in parts) + "$"
        match = re.match(regex, real)
        if not match:
            raise SystemExit("placeholder and real files differ in shape")
        for name, value in zip(names, match.groups()):
            if out.setdefault(name, value) != value:
                raise SystemExit("placeholder maps to two different real values")


def find_document(node):
    if isinstance(node, dict):
        if node.get("name") == DOC_NAME and isinstance(node.get("id"), str):
            return node["id"]
        for value in node.values():
            found = find_document(value)
            if found:
                return found
    elif isinstance(node, list):
        for value in node:
            found = find_document(value)
            if found:
                return found
    return None


def main():
    ap = argparse.ArgumentParser(description="Generate the git-ignored sandbox mapping file with real IDs.")
    ap.add_argument("--example", required=True)
    ap.add_argument("--placeholders", required=True)
    ap.add_argument("--real", required=True)
    ap.add_argument("--document", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    ignored = subprocess.run(["git", "check-ignore", "-q", args.out]).returncode == 0
    if not ignored:
        print("refusing to write: output path is not git-ignored", file=sys.stderr)
        return 1

    mapping = {}
    pair(load(args.placeholders), load(args.real), mapping)
    doc_id = find_document(load(args.document))
    if not doc_id:
        print("report document not found in the document list", file=sys.stderr)
        return 1
    mapping["<document-id>"] = doc_id

    with open(args.example, encoding="utf-8") as fh:
        lines = [ln for ln in fh.read().splitlines(keepends=True) if not ln.lstrip().startswith("#")]
    text = "# Generated by make_sandbox_mappings.py. Real IDs: git-ignored, never commit.\n" + "".join(lines)
    unknown = {p for p in ANY_PLACEHOLDER_RE.findall(text) if p not in mapping}
    if unknown:
        print("example has %d placeholder(s) with no real ID" % len(unknown), file=sys.stderr)
        return 1
    used = set(ANY_PLACEHOLDER_RE.findall(text))
    text = ANY_PLACEHOLDER_RE.sub(lambda m: mapping[m.group(0)], text)
    if ANY_PLACEHOLDER_RE.search(text):
        print("placeholder left after replacement", file=sys.stderr)
        return 1

    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s: %d distinct placeholders replaced" % (args.out, len(used)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
